// Hegel v0.9.29 embeds no darwin/amd64 library. Keep ordinary package tests
// available there without requiring an external libhegel checkout or override.
func hegelPlatformSupported(goos, goarch string) bool {
	return goos != "darwin" || goarch != "amd64"
}

func testProperty(t *testing.T, fn func(*hegel.T), opts ...hegel.Option) {
	t.Helper()
	if !hegelPlatformSupported(runtime.GOOS, runtime.GOARCH) {
		t.Skip("Hegel v0.9.29 has no embedded libhegel for darwin/amd64")
	}
	hegel.Test(t, fn, opts...)
}
