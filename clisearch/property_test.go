// propertyPermutation uses Fisher-Yates so every insertion order is reachable.
func propertyPermutation(ht *hegel.T, n int) []int {
	ht.Helper()
	order := make([]int, n)
	for i := range order {
		order[i] = i
	}
	for i := n - 1; i > 0; i-- {
		j := hegel.Draw(ht, hegel.Integers(0, i))
		order[i], order[j] = order[j], order[i]
	}
	return order
}

func TestSearchInsertionOrderProperty(t *testing.T) {
	// Exercise traversal order instead of letting Cobra canonicalize both trees.
	sorting := cobra.EnableCommandSorting
	cobra.EnableCommandSorting = false
	t.Cleanup(func() { cobra.EnableCommandSorting = sorting })
	testProperty(t, func(ht *hegel.T) {
		drawnCount := hegel.Draw(ht, hegel.Integers[uint](0, math.MaxUint))
		count := max(4, int(min(drawnCount, 40))) // Bound tree materialization.
		seed := hegel.Draw(ht, hegel.Integers[uint](0, math.MaxUint))
		term := fmt.Sprintf("needle%d", seed)
		summaries := make([]string, count)
		for i := range summaries {
			// Pairs have identical evidence (ties); other pairs have different scores.
			summaries[i] = strings.Repeat(term+" ", 1+i/2) + "unrelated"
		}
		build := func(order []int) *cobra.Command {
			root := &cobra.Command{Use: "tool"}
			group := &cobra.Command{Use: "group"}
			root.AddCommand(group)
			for _, i := range order {
				group.AddCommand(runnable(fmt.Sprintf("item%02d", i), summaries[i]))
			}
			return root
		}
		first := build(propertyPermutation(ht, count))
		second := build(propertyPermutation(ht, count))
		a := clisearch.Search(first, term, 20, clisearch.Options{})
		b := clisearch.Search(second, term, 20, clisearch.Options{})
		require.Len(ht, a, min(count, 20))
		assert.Equal(ht, a, b)
	}, hegel.WithTestCases(2000), hegel.WithDatabase(t.TempDir()))
}

func TestSearchQueryOrderDoesNotChangeRankingProperty(t *testing.T) {
	testProperty(t, func(ht *hegel.T) {
		seed := hegel.Draw(ht, hegel.Integers[uint](0, math.MaxUint))
		drawnCount := hegel.Draw(ht, hegel.Integers[uint](0, math.MaxUint))
		count := max(2, int(min(drawnCount, 5))) // Bound corpus materialization.
		terms := make([]string, count)
		for i := range terms {
			terms[i] = fmt.Sprintf("term%dq%d", seed, i)
		}
		root := &cobra.Command{Use: "tool"}
		root.AddCommand(runnable("both", strings.Join(terms, " ")))
		for i, term := range terms {
			root.AddCommand(runnable(fmt.Sprintf("entry%d", i), term))
		}
		forward := clisearch.Search(root, strings.Join(terms, " "), 20, clisearch.Options{})
		// Different punctuation/case still denotes the same normalized terms.
		reordered := append(slices.Clone(terms), terms[hegel.Draw(ht, hegel.Integers(0, len(terms)-1))])
		slices.Reverse(reordered)
		reverse := clisearch.Search(root, strings.ToUpper(strings.Join(reordered, "! ")), 20, clisearch.Options{})
		permuted := make([]string, len(reordered))
		for i, j := range propertyPermutation(ht, len(reordered)) {
			permuted[i] = reordered[j]
		}
		shuffled := clisearch.Search(root, strings.Join(permuted, " "), 20, clisearch.Options{})
		require.Len(ht, forward, len(terms)+1)
		assert.Equal(ht, "tool both", forward[0].Command)
		assert.Equal(ht, forward, reverse)
		assert.Equal(ht, forward, shuffled)
	}, hegel.WithTestCases(2000), hegel.WithDatabase(t.TempDir()))
}

