func propertyQuery(ht *hegel.T) string {
	ht.Helper()
	text := hegel.Draw(ht, hegel.OneOf(hegel.Text(), hegel.SampledFrom([]string{"needle", "remove", "TICKET!", "migrat", "comment", "the and", ""})))
	raw := hegel.Draw(ht, hegel.Lists(hegel.Integers[byte](0, 255)))
	// Bound materialized work, rather than narrowing the generated byte domain.
	raw = raw[:min(len(raw), 2048)]
	if hegel.Draw(ht, hegel.Booleans()) {
		return text
	}
	return string(raw)
}

