func TestSearchAuthoredUsageProperty(t *testing.T) {
	testProperty(t, func(ht *hegel.T) {
		suffix := hegel.Draw(ht, hegel.Text())
		explicit := hegel.Draw(ht, hegel.Booleans())
		root := &cobra.Command{Use: "tool"}
		group := &cobra.Command{Use: "group"}
		root.AddCommand(group)
		leaf := runnable("one "+suffix, "quartz")
		group.AddCommand(leaf)
		leaf.Annotations = map[string]string{cobra.CommandDisplayNameAnnotation: hegel.Draw(ht, hegel.Text())}
		leaf.Flags().Bool("verbose", false, "extra output")
		disabled := hegel.Draw(ht, hegel.Booleans())
		leaf.DisableFlagsInUseLine = disabled
		if explicit {
			leaf.Use += " [flags]"
		}
		// Disable automatic flags so Cobra's independent UseLine oracle preserves
		// all authored syntax, even when the generated suffix already has [flags].
		oracle := *leaf
		oracle.DisableFlagsInUseLine = true
		got := clisearch.Search(root, "quartz", 20, clisearch.Options{})
		require.Len(ht, got, 1)
		assert.Equal(ht, oracle.UseLine(), got[0].Usage)
		assert.Equal(ht, disabled, leaf.DisableFlagsInUseLine)
	}, hegel.WithTestCases(1000), hegel.WithDatabase(t.TempDir()))
}

type failAtWriter struct {
	remaining int
	err       error
}

func (w *failAtWriter) Write(p []byte) (int, error) {
	if w.remaining == 0 {
		return 0, w.err
	}
	w.remaining--
	return len(p), nil
}

