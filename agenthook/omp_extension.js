import { existsSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

// OMP loads extensions from their real paths, including in bundled builds:
// https://github.com/can1357/oh-my-pi/blob/v19.2.1/packages/coding-agent/src/extensibility/plugins/legacy-pi-compat.ts#L2787-L2820
const piModulePath = fileURLToPath(new URL("./agenthook.js", import.meta.url));

function legacyPiModule() {
	let source;
	try { source = readFileSync(piModulePath, "utf8"); }
	catch (error) {
		if (error.code === "ENOENT") return false;
		throw error;
	}
	const lines = source.split(/\r?\n/);
	if (lines[0] !== "// Generated by go.kenn.io/kit/agenthook; Install and Uninstall rewrite this file.") return false;
	const begin = lines.indexOf("// agenthook:begin"), end = lines.indexOf("// agenthook:end", begin + 1);
	if (begin < 0 || end < 0) return false;
	const module = lines.slice(end + 1);
	return module.some((line) => line.includes("export default function (pi) {")) &&
		!module.some((line) => line.trim() === "// agenthook:omp-guarded");
}

// OMP v19.2.1 event contracts:
// https://github.com/can1357/oh-my-pi/blob/v19.2.1/packages/coding-agent/src/extensibility/shared-events.ts#L26-L83
// https://github.com/can1357/oh-my-pi/blob/v19.2.1/packages/coding-agent/src/extensibility/extensions/types.ts#L1455-L1461
// https://github.com/can1357/oh-my-pi/blob/v19.2.1/packages/coding-agent/src/extensibility/extensions/types.ts#L1585-L1650
// https://github.com/can1357/oh-my-pi/blob/v19.2.1/packages/coding-agent/src/extensibility/shared-events.ts#L121-L132
export default function (omp) {
	let announced = null, compatibilityChecked = false, incompatible = false;
	const identity = (ctx) => ({ id: ctx.sessionManager.getSessionId(), file: ctx.sessionManager.getSessionFile(), cwd: ctx.cwd });
	const payload = (name, ctx, extra = {}) => {
		const { id, file, cwd } = identity(ctx);
		return { hook_event_name: name, session_id: id, cwd, ...(file ? { transcript_path: file } : {}), ...extra };
	};
	const valid = (name, value) => {
		const allowed = name === "PreToolUse" ? ["block", "reason", "additionalContext"] : name === "Stop" ? ["decision", "reason"] : name === "PostToolUse" || name === "PostToolUseFailure" ? ["additionalContext"] : [];
		return Object.keys(value).every((key) => allowed.includes(key)) &&
			(value.block === undefined || typeof value.block === "boolean") &&
			(value.reason === undefined || typeof value.reason === "string") &&
			(value.additionalContext === undefined || typeof value.additionalContext === "string") &&
			(value.decision === undefined || value.decision === "block") &&
			(value.reason === undefined || (name === "Stop" ? value.decision === "block" : value.block === true));
	};
	const on = (name, fn) => omp.on(name, async (event, ctx) => {
		if (ctx.mode !== "tui" || ctx.agent?.kind !== "main") return;
		if (!compatibilityChecked) {
			compatibilityChecked = true;
			try {
				incompatible = legacyPiModule();
				if (incompatible) ctx.ui.notify(`agenthook: legacy Pi extension ${piModulePath} can duplicate omp events; reinstall existing Pi registrations with updated Kit, then restart omp`, "error");
			} catch (error) {
				ctx.ui.notify(`agenthook: cannot inspect Pi extension ${piModulePath}: ${error.message}`, "error");
			}
		}
		if (incompatible) return;
		const deadline = Date.now() + 25000;
		const run = async (eventName, data, matcher, signal) => {
			const invalid = [], responses = [];
			const stop = (value) => {
				if (!valid(eventName, value)) { invalid.push("invalid " + eventName + " response"); return false; }
				responses.push(value);
				return value.block === true || value.decision === "block";
			};
			const result = await runHooks(eventName, data, { collect: true, matcher, signal, budgetMs: Math.max(0, deadline - Date.now()), stop });
			for (const failure of [...result.failures, ...invalid]) ctx.ui.notify("agenthook: " + failure, "error");
			const block = responses.find((value) => value.block === true || value.decision === "block");
			if (block) return block;
			const contexts = [];
			for (const value of responses) {
				if (value.additionalContext?.trim()) contexts.push(value.additionalContext);
			}
			return contexts.length ? { additionalContext: contexts.join("\n\n") } : undefined;
		};
		try { return await fn(event, ctx, run); }
		catch (error) { ctx.ui.notify("agenthook: " + error.message, "error"); }
	});
	// OMP assigns a session-manager ID before its lazy transcript write:
	// https://github.com/can1357/oh-my-pi/blob/v19.2.1/packages/coding-agent/src/session/session-manager.ts#L3357-L3374
	on("session_start", async (_event, ctx, run) => {
		announced = identity(ctx);
		await run("SessionStart", payload("SessionStart", ctx, { source: announced.file && existsSync(announced.file) ? "resume" : "startup" }));
	});
	const replace = async (event, ctx, run) => {
		const now = identity(ctx);
		if (announced?.id === now.id) return;
		if (announced) {
			await run("SessionEnd", { hook_event_name: "SessionEnd", session_id: announced.id, ...(announced.file ? { transcript_path: announced.file } : {}), cwd: announced.cwd, reason: event.reason === "new" ? "clear" : event.reason === "resume" ? "resume" : "other" });
		}
		announced = now;
		await run("SessionStart", payload("SessionStart", ctx, { source: event.reason === "new" ? "clear" : event.reason === "resume" ? "resume" : "fork" }));
	};
	on("session_switch", replace);
	on("session_branch", replace);
	on("input", async (event, ctx, run) => {
		if (event.source !== "interactive" || typeof event.text !== "string" || !event.text) return;
		await run("UserPromptSubmit", payload("UserPromptSubmit", ctx, { prompt: event.text }));
	});
	const toolFields = (event) => ({ tool_name: event.toolName, tool_use_id: event.toolCallId, tool_input: event.input });
	on("tool_call", (event, ctx, run) => run("PreToolUse", payload("PreToolUse", ctx, toolFields(event)), event.toolName));
	on("tool_result", async (event, ctx, run) => {
		const name = event.isError ? "PostToolUseFailure" : "PostToolUse";
		const text = event.content?.filter((part) => part.type === "text").map((part) => part.text).join("\n");
		const result = event.isError ? { error: text || (event.details?.exitCode != null ? `exit code ${event.details.exitCode}` : "tool failed") } : { tool_response: { content: event.content, details: event.details } };
		return run(name, payload(name, ctx, { ...toolFields(event), ...result }), event.toolName);
	});
	on("session_stop", (event, ctx, run) => {
		const content = event.last_assistant_message?.content;
		const text = typeof content === "string" ? content : Array.isArray(content) ? content.filter((part) => part.type === "text").map((part) => part.text).join("\n") : "";
		return run("Stop", payload("Stop", ctx, { ...(event.session_file ? { transcript_path: event.session_file } : {}), stop_hook_active: !!event.stop_hook_active, ...(text ? { last_assistant_message: text } : {}) }), undefined, event.signal);
	});
}
